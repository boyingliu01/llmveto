#!/usr/bin/env node
/**
 * ccn-report — 用 lizard 测量圈复杂度，并写出/刷新 Gate 3 的棘轮基线。
 *
 * 为什么这个文件必须存在：xp-gate 的 Gate 3 一旦发现 `.ccn-baseline.json`，
 * 就改为棘轮模式，并要求 `scripts/ccn-report.cjs` 提供 `--csv-verified`；
 * 缺了它 Gate 3 **fail-closed**（拒绝出结论，而不是出一个未核实的结论）。
 * 本仓库此前没有这个文件，所以 Gate 3 要么把存量债务当新代码全判红，要么干脆不评级。
 *
 * 复杂度**只有一个权威引擎：lizard**。本脚本不做任何自己的计数——
 * 第一版曾用正则数决策点自造公式，结果与 lizard 差一个常数：同一份代码基线记 2、
 * 门禁算 3，棘轮永远报"变差"。这里只做两件事：逐文件调用 lizard，以及在
 * "跨度不可能"时用花括号配平重新切出真实函数体后**仍然交给 lizard** 重算。
 *
 * 逐文件而不是批量：批量模式下 lizard 会把后续文件的分支记到前一个函数的跨度里，
 * 实测同一函数批量报 728、逐文件报 10。棘轮比的是每函数一个数，口径必须一致。
 *
 * 用法：
 *   node scripts/ccn-report.cjs                  # 打印超阈值清单
 *   node scripts/ccn-report.cjs --json           # 机器可读
 *   node scripts/ccn-report.cjs --write-baseline # 写 .ccn-baseline.json
 *   lizard --csv <file> | node scripts/ccn-report.cjs --csv-verified batch --root <repo>
 *                                                # Gate 3 的核验接口：输入输出都是 lizard CSV
 */
"use strict";

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const BASELINE_PATH = path.join(ROOT, ".ccn-baseline.json");

/** 本仓库源码面：TS/JS。 */
const SOURCE_EXT = /\.(ts|tsx|js|jsx|mjs|cjs)$/i;
/** 不进基线的目录：产物与本脚本自己的临时物。 */
const SKIP_DIRS = new Set(["node_modules", "dist", "coverage", ".git", ".worktrees", "var", ".xp-gate", ".sprint-history"]);
/** Gate 3 的默认阈值（.xp-gate/ccn-threshold > XP_GATE_CCN_THRESHOLD > 5）。 */
const DEFAULT_THRESHOLD = 5;
/** 与 Gate 3 评级的文件集合一致：一侧更宽就会把存量当新函数（无法修复的假红）。 */
const BASELINE_ROOTS = ["src", "testkit", "bench", "scripts"];
/** 超过这个跨度就不是真实函数体：lizard 在部分输入上丢了花括号平衡。 */
const SPAN_ARTEFACT_MAX_LINES = 250;

/** 基线文件的说明头：把"为什么有这份文件"钉在文件里，而不是只写在提交信息里。 */
const BASELINE_COMMENT = [
  "Gate 3 cyclomatic-complexity ratchet baseline (xp-gate ccn-ratchet).",
  "Generated by scripts/ccn-report.cjs --write-baseline; do not hand-edit.",
  "A recorded function passes at its recorded CCN or lower and BLOCKS if it grows;",
  "functions with no entry are new code and still face the flat threshold.",
  "All numbers come from lizard -- one process per file -- because batch mode",
  "inflates spans across file boundaries and would make them incomparable.",
];

/** 最小 CSV 解析：lizard 的签名列含逗号，但在引号内。 */
function splitCsv(line) {
  const out = [];
  let cur = "";
  let quoted = false;
  for (const ch of line) {
    if (ch === '"') quoted = !quoted;
    else if (ch === "," && !quoted) {
      out.push(cur);
      cur = "";
    } else cur += ch;
  }
  out.push(cur);
  return out;
}

/** 一行 lizard CSV → { name, ccn, path, start, end }；不是函数行返回 null。 */
/** 有效 CCN：正有限数。 */
function validCcn(value) {
  const n = Number(value);
  return Number.isFinite(n) && n > 0 ? n : undefined;
}

/** 行里描述的源文件路径：优先第 7 列，缺失则从 `fn@start-end@path` 里取。 */
function sourcePathOf(cols) {
  return cols[6] || (cols[5] || "").split("@").pop();
}

function rowOf(cols) {
  if (cols.length < 11) return null;
  const ccn = validCcn(cols[1]);
  const name = cols[7];
  const sourcePath = sourcePathOf(cols);
  if (ccn === undefined || !name || !sourcePath) return null;
  return { name, ccn, path: sourcePath, start: Number(cols[9]), end: Number(cols[10]), cols };
}

/** 目录项 → 是目录且不在跳过集合里。 */
function isWalkableDir(entry) {
  return entry.isDirectory() && !SKIP_DIRS.has(entry.name);
}

/** 递归收集候选源文件。 */
function walk(dir, out) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    if (isWalkableDir(e)) walk(path.join(dir, e.name), out);
    else if (SOURCE_EXT.test(e.name)) out.push(path.join(dir, e.name));
  }
  return out;
}

/** 逐文件测量：**一个进程一个文件**，避免批量模式的跨度污染。 */
function measureFileArgs(files) {
  return files.map((f) => [f]);
}

/** 调 lizard 拿某文件的 CSV；失败抛出（不静默返回空串，那会被读成"没有问题"）。 */
function lizardCsv(file) {
  try {
    return execFileSync("lizard", ["--csv", file], { encoding: "utf8", cwd: ROOT });
  } catch (err) {
    throw new Error(`lizard failed on ${path.relative(ROOT, file)}: ${err instanceof Error ? err.message : String(err)}`);
  }
}

/** 一行 CSV → { file, name, ccn }；不可解析返回 null。 */
function fnRowOf(cols) {
  const row = rowOf(cols);
  return row === null ? null : { name: row.name, ccn: row.ccn };
}

/** 读源码行（相对仓库根）；不可读返回 null。 */
function readSourceLines(root, rel) {
  let text = null;
  try {
    text = fs.readFileSync(path.join(root, rel), "utf8");
  } catch {
    return null;
  }
  return text.split(/\r?\n/);
}

/** 一段文本对花括号深度的净变化。 */
function depthDelta(text) {
  let delta = 0;
  for (const ch of text) {
    if (ch === "{") delta += 1;
    else if (ch === "}") delta -= 1;
  }
  return delta;
}

/** 从第 from 行、第 openCol 列的花括号起向下配平；配不平返回 null。 */
function braceMatchEnd(srcLines, from, openCol) {
  let depth = 0;
  for (let j = from; j < srcLines.length; j += 1) {
    depth += depthDelta(j === from ? srcLines[j].slice(openCol) : srcLines[j]);
    if (depth === 0) return j;
  }
  return null;
}

/** 该行能否当函数体起点：必须含 `{`；距起点 2 行以上还须能对上函数名。 */
function bodyStartCol(srcLines, i, name, startLine) {
  const line = srcLines[i];
  if (i > startLine + 2 && !line.includes(name)) return -1;
  return line.indexOf("{");
}

/** 从名字行附近切出真实函数体（花括号配平）；找不到返回 null。 */
function locateBody(srcLines, name, startLine) {
  const limit = Math.min(srcLines.length, startLine + 40);
  for (let i = Math.max(0, startLine - 1); i < limit; i += 1) {
    const openCol = bodyStartCol(srcLines, i, name, startLine);
    if (openCol === -1) continue;
    const end = braceMatchEnd(srcLines, i, openCol);
    return end === null ? null : { start: i, end };
  }
  return null;
}

/** 把一段源码交给 lizard 重算，取其中最大 CCN；失败返回 undefined。 */
function measureWithLizard(lines) {
  const tmp = path.join(os.tmpdir(), `ccn-body-${process.pid}-${Math.random().toString(36).slice(2)}.ts`);
  try {
    fs.writeFileSync(tmp, lines.join("\n"), "utf8");
    const rows = lizardCsv(tmp)
      .split("\n")
      .map(splitCsv)
      .map(fnRowOf)
      .filter((r) => r !== null);
    return rows.length === 0 ? undefined : Math.max(...rows.map((r) => r.ccn));
  } catch {
    return undefined;
  } finally {
    try {
      fs.unlinkSync(tmp);
    } catch {
      /* best effort */
    }
  }
}

/** 带缓存地读某文件源码行。 */
function cachedLines(cache, root, rel) {
  if (!cache.has(rel)) cache.set(rel, readSourceLines(root, rel));
  return cache.get(rel);
}

/**
 * 核验一行的 CCN。
 *
 * 只有"跨度不可能"时才重算：正常行直接采信 lizard（它才是权威引擎）。
 * 重算也不是自造公式——先用花括号配平整出真实函数体，再交给 lizard。
 */
/** 跨度是否可疑（lizard 丢了花括号平衡的典型形态）。 */
function spanSuspicious(row) {
  const declaredSpan = row.end > row.start ? row.end - row.start + 1 : 0;
  return declaredSpan > SPAN_ARTEFACT_MAX_LINES;
}

/** 切出真实函数体并用 lizard 重算；任何一步做不到就记 unverified。 */
function recomputeFromBody(row, cache, root, tally) {
  const srcLines = cachedLines(cache, root, row.path);
  const body = srcLines === null ? null : locateBody(srcLines, row.name, row.start);
  const recomputed = body === null ? undefined : measureWithLizard(srcLines.slice(body.start, body.end + 1));
  if (recomputed === undefined) tally.unverified += 1;
  return recomputed;
}

function verifiedCcn(row, cache, root, tally) {
  return spanSuspicious(row) ? recomputeFromBody(row, cache, root, tally) : row.ccn;
}

/** 一行 lizard CSV → 核验后的行（不可核验则原样返回）。 */
function verifyRow(line, root, cache, tally) {
  const cols = splitCsv(line);
  const row = rowOf(cols);
  if (row === null) return line;
  const ccn = verifiedCcn(row, cache, root, tally);
  if (ccn === undefined || ccn === row.ccn) return line;
  cols[1] = String(ccn);
  tally.corrected += 1;
  return cols.join(",");
}

/** 对整段 CSV 做核验（同步）：--write-baseline 与 collect 都走这里。 */
function verifyCsvText(csv, root) {
  const cache = new Map();
  const tally = { unverified: 0, corrected: 0 };
  const out = csv.split(/\r?\n/).map((line) => (line.trim() ? verifyRow(line, root, cache, tally) : line));
  return { csv: out.join("\n"), tally };
}

/** 收集全仓函数的 { file, name, ccn }（已核验）。 */
/** 某个文件核验后的函数行（带相对路径）。 */
function rowsOfFile(file) {
  const rel = path.relative(ROOT, file).split(path.sep).join("/");
  const rows = [];
  for (const line of verifyCsvText(lizardCsv(file), ROOT).csv.split("\n")) {
    const row = line.trim() ? rowOf(splitCsv(line)) : null;
    if (row !== null) rows.push({ file: rel, name: row.name, ccn: row.ccn });
  }
  return rows;
}

function collect() {
  const files = [];
  for (const root of BASELINE_ROOTS) walk(path.join(ROOT, root), files);
  return measureFileArgs(files.sort()).flatMap(([file]) => rowsOfFile(file));
}

/** 正整数才接受（非法值绝不静默变成 0）。 */
function positiveInt(value) {
  const n = Number(value);
  return Number.isInteger(n) && n > 0 ? n : undefined;
}

/** 阈值三级覆盖：.xp-gate/ccn-threshold > XP_GATE_CCN_THRESHOLD > 默认 5。 */
function threshold() {
  const overridePath = path.join(ROOT, ".xp-gate", "ccn-threshold");
  const fromFile = fs.existsSync(overridePath) ? positiveInt(fs.readFileSync(overridePath, "utf8").trim()) : undefined;
  return fromFile ?? positiveInt(process.env.XP_GATE_CCN_THRESHOLD) ?? DEFAULT_THRESHOLD;
}

/** 写基线：每个函数一个上限，按路径排序保证 diff 可读。 */
function writeBaseline(rows) {
  const entries = {};
  for (const r of rows) entries[`${r.file}::${r.name}`] = r.ccn;
  const baseline = {
    $comment: BASELINE_COMMENT,
    population: { roots: BASELINE_ROOTS, extensions: [".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"] },
    entries: Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b))),
  };
  fs.writeFileSync(BASELINE_PATH, `${JSON.stringify(baseline, null, 2)}\n`, "utf8");
  return Object.keys(entries).length;
}

/** Gate 3 的核验接口：stdin 是 lizard CSV，stdout 必须是同样的 CSV。 */
function csvVerified(root) {
  let input = "";
  process.stdin.setEncoding("utf8");
  process.stdin.on("data", (c) => {
    input += c;
  });
  process.stdin.on("end", () => {
    const { csv, tally } = verifyCsvText(input, root);
    if (tally.unverified > 0) console.error(`WARN - ${tally.unverified} row(s) could not be span-verified`);
    process.stdout.write(csv);
  });
}

function main(argv) {
  const rows = collect();
  if (argv.includes("--write-baseline")) {
    const n = writeBaseline(rows);
    console.log(`baseline written: ${n} functions -> ${path.relative(ROOT, BASELINE_PATH)}`);
    return 0;
  }
  if (argv.includes("--json")) {
    console.log(JSON.stringify(rows, null, 2));
    return 0;
  }
  const limit = threshold();
  const over = rows.filter((r) => r.ccn > limit);
  console.log(`measured ${rows.length} functions across ${new Set(rows.map((r) => r.file)).size} files`);
  console.log(`over threshold (CCN > ${limit}): ${over.length}`);
  for (const r of over.sort((a, b) => b.ccn - a.ccn)) console.log(`  ${String(r.ccn).padStart(3)}  ${r.file}::${r.name}`);
  return 0;
}

if (require.main === module) {
  const argv = process.argv.slice(2);
  const csvIdx = argv.indexOf("--csv-verified");
  if (csvIdx >= 0) {
    const rootIdx = argv.indexOf("--root");
    csvVerified(rootIdx >= 0 ? path.resolve(argv[rootIdx + 1]) : ROOT);
  } else {
    process.exit(main(argv));
  }
}

module.exports = { measureFileArgs, splitCsv, rowOf, collect, writeBaseline, threshold, verifyCsvText, BASELINE_ROOTS };
