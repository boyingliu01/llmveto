#!/usr/bin/env node
/**
 * ccn-report — 逐文件测量圈复杂度，并据以写出/核对 Gate 3 的棘轮基线。
 *
 * 为什么按文件逐个测（而不是 lizard 批量模式）：
 * 批量模式下 lizard 会把一个函数的"跨度"吃进下一个文件的分支，实测同一份代码
 * 批量报 CCN=728、逐文件报 10。棘轮比的是每函数一个数，批量口径下这个数不可信。
 * 因此 `measureFileArgs` 必须**永远只产出一个位置参数**，由 `ccn-report.test.cjs` 钉住。
 *
 * 为什么需要它：xp-gate 的 Gate 3 在发现 `.ccn-baseline.json` 时会改为棘轮模式，
 * 并在 `scripts/ccn-report.cjs` 缺失时 **fail-closed**（宁可拒绝出结论，也不出未核实的结论）。
 * 本仓库此前没有这个文件，所以 Gate 3 要么把存量债务当新代码全判红，
 * 要么拒绝评级——两种都不对。
 *
 * 用法：
 *   node scripts/ccn-report.cjs                  # 打印超阈值清单
 *   node scripts/ccn-report.cjs --write-baseline # 写 .ccn-baseline.json
 *   node scripts/ccn-report.cjs --json           # 机器可读
 */
"use strict";

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const BASELINE_PATH = path.join(ROOT, ".ccn-baseline.json");

/** 只测 TS/JS：本仓库的源码面就是这两类（与 Gate 3 的语言适配器一致）。 */
const SOURCE_EXT = /\.(ts|tsx|js|jsx|mjs|cjs)$/i;
/** 测试与构建产物不进基线：它们不是要维护的生产代码。 */
const SKIP_DIRS = new Set(["node_modules", "dist", "coverage", ".git", ".worktrees", "var", ".xp-gate"]);
/** Gate 3 的默认阈值（.xp-gate/ccn-threshold > XP_GATE_CCN_THRESHOLD > 5）。 */
const DEFAULT_THRESHOLD = 5;
/**
 * 基线记录的搜索面。与 Gate 3 评级的文件集合保持一致：
 * 任何一侧更宽都会让"存量"被当成"新函数"（无法修复的假红）。
 */
const BASELINE_ROOTS = ["src", "testkit", "bench", "scripts"];

function walk(dir, out) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name)) continue;
      walk(path.join(dir, e.name), out);
    } else if (SOURCE_EXT.test(e.name)) {
      out.push(path.join(dir, e.name));
    }
  }
  return out;
}

/** 逐文件测量：**一个进程一个文件**，避免批量模式的跨度污染。 */
function measureFileArgs(files) {
  return files.map((f) => [f]);
}

function lizardCsv(file) {
  try {
    return execFileSync("lizard", ["--csv", file], { encoding: "utf8", cwd: ROOT });
  } catch (err) {
    throw new Error(`lizard failed on ${path.relative(ROOT, file)}: ${err instanceof Error ? err.message : String(err)}`);
  }
}

/** CSV 行 → { file, name, ccn }；列序见 lizard 1.2x：NLOC, CCN, token, param, len, "fn@span@file", file, name, sig, start, end。 */
function rowsOf(file, csv) {
  const rows = [];
  for (const line of csv.split("\n")) {
    if (!line.trim()) continue;
    const cols = splitCsv(line);
    if (cols.length < 11) continue;
    const ccn = Number(cols[1]);
    const name = cols[7];
    if (!Number.isFinite(ccn) || !name) continue;
    rows.push({ file: path.relative(ROOT, file).split(path.sep).join("/"), name, ccn });
  }
  return rows;
}

/** 最小 CSV 解析：lizard 的签名列含逗号但在引号内。 */
function splitCsv(line) {
  const out = [];
  let cur = "";
  let inQuotes = false;
  for (const ch of line) {
    if (ch === '"') inQuotes = !inQuotes;
    else if (ch === "," && !inQuotes) {
      out.push(cur);
      cur = "";
    } else cur += ch;
  }
  out.push(cur);
  return out;
}

function collect() {
  const files = [];
  for (const root of BASELINE_ROOTS) walk(path.join(ROOT, root), files);
  const rows = [];
  for (const [file] of measureFileArgs(files.sort())) rows.push(...rowsOf(file, lizardCsv(file)));
  return rows;
}

function threshold() {
  const overridePath = path.join(ROOT, ".xp-gate", "ccn-threshold");
  if (fs.existsSync(overridePath)) {
    const v = Number(fs.readFileSync(overridePath, "utf8").trim());
    if (Number.isInteger(v) && v > 0) return v;
  }
  const env = Number(process.env.XP_GATE_CCN_THRESHOLD);
  if (Number.isInteger(env) && env > 0) return env;
  return DEFAULT_THRESHOLD;
}

function writeBaseline(rows) {
  const entries = {};
  for (const r of rows) entries[`${r.file}::${r.name}`] = r.ccn;
  const baseline = {
    $comment: [
      "Gate 3 cyclomatic-complexity ratchet baseline (xp-gate ccn-ratchet).",
      "Generated by scripts/ccn-report.cjs --write-baseline; do not hand-edit.",
      "A recorded function passes at its recorded CCN or lower and BLOCKS if it grows;",
      "functions with no entry are new code and still face the flat threshold.",
      "Measured one lizard process per file: batch mode inflates spans across file",
      "boundaries and makes these numbers incomparable with a per-function gate.",
    ],
    population: { roots: BASELINE_ROOTS, extensions: [".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"] },
    entries: Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b))),
  };
  fs.writeFileSync(BASELINE_PATH, `${JSON.stringify(baseline, null, 2)}\n`, "utf8");
  return Object.keys(entries).length;
}

function main(argv) {
  const rows = collect();
  if (argv.includes("--write-baseline")) {
    const n = writeBaseline(rows);
    console.log(`baseline written: ${n} functions -> ${path.relative(ROOT, BASELINE_PATH)}`);
    return 0;
  }
  if (argv.includes("--json")) {
    console.log(JSON.stringify(rows, null, 2));
    return 0;
  }
  const over = rows.filter((r) => r.ccn > threshold());
  console.log(`measured ${rows.length} functions across ${new Set(rows.map((r) => r.file)).size} files`);
  console.log(`over threshold (CCN > ${threshold()}): ${over.length}`);
  for (const r of over.sort((a, b) => b.ccn - a.ccn)) console.log(`  ${String(r.ccn).padStart(3)}  ${r.file}::${r.name}`);
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { measureFileArgs, splitCsv, rowsOf, collect, writeBaseline, threshold, BASELINE_ROOTS };
